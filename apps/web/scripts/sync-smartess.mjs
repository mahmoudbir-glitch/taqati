// The web app is deployed on its own (it cannot import workspace packages), so
// the SmartESS client and mapper it needs are copies of the API's sources.
// Run `pnpm sync:smartess` after changing them; `--check` fails when they differ.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../../..");
const target = resolve(root, "apps/web/lib/server/smartess");

const files = [
  { from: "apps/api/src/smartess/smartess.client.ts", to: "client.ts" },
  { from: "apps/api/src/smartess/smartess.mapper.ts", to: "mapper.ts" },
  { from: "packages/shared/src/telemetry.ts", to: "telemetry-message.ts" },
];

const rewrite = (source) =>
  source
    .replace(/\r\n/g, "\n")
    .replace(`from "@taqati/shared"`, `from "./telemetry-message"`)
    .replace(`from "./smartess.client"`, `from "./client"`);

const check = process.argv.includes("--check");
let stale = false;
mkdirSync(target, { recursive: true });
for (const { from, to } of files) {
  const expected = `// GENERATED by apps/web/scripts/sync-smartess.mjs from ${from}. Do not edit.\n${rewrite(readFileSync(resolve(root, from), "utf8"))}`;
  const path = resolve(target, to);
  if (check) {
    let current = "";
    try {
      current = readFileSync(path, "utf8").replace(/\r\n/g, "\n");
    } catch {
      // A missing copy is stale.
    }
    if (current !== expected) {
      stale = true;
      console.error(`stale: apps/web/lib/server/smartess/${to} (run pnpm sync:smartess)`);
    }
  } else {
    writeFileSync(path, expected);
  }
}
if (stale) process.exit(1);
console.log(check ? "SmartESS copies are up to date" : "SmartESS copies written");
